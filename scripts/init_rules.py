#!/usr/bin/env python3
"""Create docs/code-review/rules.yaml for the current repository.

Usage: init_rules.py [--force] [--gitignore] [--dry-run]

Detects stacks from project markers, writes the commented default configuration with the
detected rulesets enabled, and (with --gitignore) adds the report directory to .gitignore.
"""
from __future__ import annotations

import argparse
import re

from _common import (PROJECT_CONFIG, RULESETS_DIR, _yaml, git, glob_match, repo_root)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="overwrite an existing rules.yaml")
    ap.add_argument("--gitignore", action="store_true", help="add the report directory to .gitignore")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = repo_root()
    files = [p for p in git("ls-files", "-z", "--cached", "--others", "--exclude-standard", cwd=root).split("\0") if p]
    detected = []
    for d in sorted(RULESETS_DIR.iterdir()):
        if d.name.startswith("_") or not (d / "detect.yaml").is_file():
            continue
        det = _yaml.load(d / "detect.yaml")
        markers = det.get("project_markers") or []
        hits = [p for p in files if glob_match(p, [f"**/{m}" for m in markers])]
        if hits:
            detected.append((d.name, len(hits), sorted(hits)[:3]))

    template = (RULESETS_DIR / "_base" / "defaults.yaml").read_text(encoding="utf-8")
    ids = [d for d, _, _ in detected]
    value = "[" + ", ".join(ids) + "]" if ids else "null"
    text = re.sub(r"(?m)^rulesets: null.*$", f"rulesets: {value}", template)
    text = text.replace("# Copy to docs/code-review/rules.yaml (or run the review-init skill) and adjust.\n",
                        "# Generated by review-init. Adjust freely; removed keys fall back to plugin defaults.\n")
    if any(p.startswith("docs/superpowers/") for p in files) is False:
        text = text.replace("  # Spec/plan documents are discovered",
                            "  # (no docs/superpowers/ found — set your own directories)\n  # Spec/plan documents are discovered")

    target = root / PROJECT_CONFIG
    print("detected stacks: " + (", ".join(f"{d} ({n} markers, e.g. {', '.join(ex)})" for d, n, ex in detected) or "none"))
    if args.dry_run:
        print(text)
        return
    if target.exists() and not args.force:
        print(f"{PROJECT_CONFIG} already exists — not overwritten (use --force)")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        print(f"wrote {PROJECT_CONFIG}")

    if args.gitignore:
        cfg = _yaml.loads(text)
        entry = cfg.get("report_dir", "docs/code-review/reports").strip("/") + "/"
        gi = root / ".gitignore"
        current = gi.read_text(encoding="utf-8") if gi.exists() else ""
        if entry in [l.strip().lstrip("/") for l in current.splitlines()]:
            print(f".gitignore already contains {entry}")
        else:
            with open(gi, "a", encoding="utf-8") as fh:
                fh.write(("" if current.endswith("\n") or not current else "\n") + f"{entry}\n")
            print(f"added {entry} to .gitignore")


if __name__ == "__main__":
    main()
